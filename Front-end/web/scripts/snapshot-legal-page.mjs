/**
 * Archive the rendered text of a legal page to docs/legal/<key>-<version>.md.
 *
 * WHY GENERATE RATHER THAN TRANSCRIBE
 * The archived file is the evidentiary copy: when an order records
 * `legalAcceptance.termsVersion = '2026-09-03'`, this file is what that version
 * NAMES. Hand-transcribing it means the archive says what somebody believed the
 * page said. Scraping the running page means it says what a buyer actually saw
 * — which is the only property that matters if the arbitration clause in §17B
 * is ever tested.
 *
 * USAGE
 *   npm run build && npm start          # in one shell
 *   npm run snapshot-legal -- terms 2026-09-03 [http://localhost:3000]
 *
 * Refuses to overwrite an existing snapshot. A shipped version is immutable; if
 * the text changed, that IS a new version — bump it in
 * Back-end/server/config/legalDocuments.js and cut a fresh file.
 */

import { writeFileSync, existsSync, mkdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const [key, version, origin = 'http://localhost:3000'] = process.argv.slice(2);

if (!key || !version) {
  console.error('usage: snapshot-legal-page.mjs <key> <version> [origin]');
  process.exit(1);
}

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const outDir = join(REPO, 'docs', 'legal');
const outFile = join(outDir, `${key}-${version}.md`);

if (existsSync(outFile)) {
  console.error(`refusing to overwrite ${outFile} — a shipped version is immutable, cut a new one`);
  process.exit(1);
}

const url = `${origin}/${key}`;
const res = await fetch(url);
if (!res.ok) {
  console.error(`GET ${url} → ${res.status}`);
  process.exit(1);
}
const raw = await res.text();

const unescape = (s) =>
  s.replace(/&quot;/g, '"').replace(/&apos;|&#x27;/g, "'")
   .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
   .replace(/&#x2F;/g, '/').replace(/&nbsp;/g, ' ');

const start = raw.indexOf('<h1');
const lastUpdatedAt = raw.indexOf('Last Updated');
const end = raw.indexOf('</section>', lastUpdatedAt === -1 ? start : lastUpdatedAt);
if (start === -1 || end === -1) {
  console.error('could not locate the document body — did the page layout change?');
  process.exit(1);
}
const frag = raw.slice(start, end);

const out = [];
const seen = new Set();
// Walk rendered elements in document order. The inline em-dash <span> inside a
// bullet is decoration, not text.
for (const m of frag.matchAll(/<(h1|h2|p|li)\b[^>]*>([\s\S]*?)<\/\1>/g)) {
  const [, tag, inner] = m;
  const text = unescape(inner.replace(/<span class="text-gold[^"]*">—<\/span>/g, '').replace(/<[^>]+>/g, ''))
    .replace(/\s+/g, ' ')
    .trim();
  if (!text) continue;
  const dedupe = `${tag}:${text}`;
  if (seen.has(dedupe)) continue;
  seen.add(dedupe);
  if (tag === 'h1') out.push(`# ${text}\n`);
  else if (tag === 'h2') out.push(`\n## ${text}\n`);
  else if (tag === 'li') out.push(`- ${text}`);
  else out.push(`\n${text}`);
}

const header = `<!--
  ARCHIVED LEGAL TEXT — DO NOT EDIT.

  Rendered text of ${url.replace(origin, '')} at version ${version}. This is the evidentiary
  copy: an order recording \`legalAcceptance.${key}Version = '${version}'\` accepted THIS text.

  Generated by scripts/snapshot-legal-page.mjs (scraped from the running page, not
  transcribed) on ${new Date().toISOString().slice(0, 10)}. Never hand-edit, and never edit a
  version that has shipped — cut a new version instead.
-->

`;

mkdirSync(outDir, { recursive: true });
writeFileSync(outFile, header + out.join('\n') + '\n', 'utf8');
console.log(`wrote ${outFile} (${out.filter((l) => l.startsWith('\n## ')).length} sections)`);
