// Bundles the 3D showroom scene (src/garage/showroom/scene.src.js + three.js)
// into ONE script string the WebView runs offline — no CDN, nothing fetched at
// run time. Run `npm run build:showroom` after editing the scene or upgrading
// three; `showroom.test.mjs` fails when the committed bundle is stale.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'src/garage/showroom/scene.src.js');
const out = join(root, 'src/garage/showroom/sceneBundle.generated.ts');

/** Source + three version: what the test recomputes to spot a stale bundle. */
export function sceneSourceHash() {
  const three = JSON.parse(readFileSync(join(root, 'node_modules/three/package.json'), 'utf8')).version;
  return createHash('sha256').update(readFileSync(src)).update(`three@${three}`).digest('hex').slice(0, 16);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const result = await build({
    entryPoints: [src],
    bundle: true,
    minify: true,
    format: 'iife',
    target: ['es2019'],
    legalComments: 'none',
    write: false,
  });
  // "</script" inside the bundle would end the inline <script> tag early.
  const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
  writeFileSync(
    out,
    `// GENERATED by scripts/build-showroom.mjs — do not edit. Source: scene.src.js + three.js.\n` +
      `export const SCENE_SOURCE_HASH = ${JSON.stringify(sceneSourceHash())};\n` +
      `export const SCENE_JS: string = ${JSON.stringify(js)};\n`,
  );
  console.log(`showroom bundle: ${(js.length / 1024).toFixed(0)} KB → ${out}`);
}
